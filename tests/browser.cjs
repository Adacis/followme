 const rp=await reader.newPage();await rp.route('**/apps/followme/findCategorie',route=>route.fulfill({status:500,json:{message:'Unavailable'}}));await rp.goto(baseUrl + '/index.php/apps/followme/');
 await rp.waitForSelector('.followme-app');
 assert.equal(await rp.locator('#categoriefollowme option').count(),9);
 assert.equal(await rp.locator('.followme-settings-link').count(),0);
 const denied=await reader.request.get(baseUrl + '/index.php/apps/followme/param');assert.equal(denied.status(),403);
 const token=await rp.evaluate(()=>OC.requestToken);
 const created=await reader.request.post(baseUrl + '/index.php/apps/followme/insertActu',{headers:{requesttoken:token},data:{date:String(Math.floor(Date.now()/1000)),lien:'https://example.org/reader-test',description:'Reader contribution fixture',categorie:'News',title:'Reader browser fixture'}});
 assert.equal(created.status(),201);
 const readerId=(await created.json()).id;
